const defaultLang = "en";
let activeLang = localStorage.getItem("athomie.lang") || defaultLang;

function translatePage(lang) {
  activeLang = translations[lang] ? lang : defaultLang;
  localStorage.setItem("athomie.lang", activeLang);
  document.documentElement.lang = activeLang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[activeLang][key] || translations[defaultLang][key];
    if (value) {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === activeLang);
  });

  const selectedOption = document.querySelector("[data-option].active")?.dataset.option || "deck";
  updateOption(selectedOption);
}

function getAttribution() {
  const params = new URLSearchParams(window.location.search);
  const keys = ["utm_source", "utm_medium", "utm_campaign", "utm_content", "utm_term", "fbclid", "gclid"];
  const stored = JSON.parse(localStorage.getItem("athomie.attribution") || "{}");
  const next = {
    ...stored,
    landing_page: stored.landing_page || window.location.pathname,
    referrer: stored.referrer || document.referrer,
    last_seen_at: new Date().toISOString()
  };

  keys.forEach((key) => {
    if (params.get(key)) {
      next[key] = params.get(key);
      next.first_seen_at = next.first_seen_at || new Date().toISOString();
    }
  });

  localStorage.setItem("athomie.attribution", JSON.stringify(next));
  return next;
}

function saveLead(form) {
  const formData = new FormData(form);
  const payload = Object.fromEntries(formData.entries());
  payload.language = activeLang;
  payload.attribution = getAttribution();
  payload.created_at = new Date().toISOString();

  const leads = JSON.parse(localStorage.getItem("athomie.leads") || "[]");
  leads.push(payload);
  localStorage.setItem("athomie.leads", JSON.stringify(leads));
  return payload;
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => translatePage(button.dataset.lang));
});

document.querySelector("#leadForm").addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = document.querySelector("#formStatus");

  if (form.website.value) {
    status.textContent = "";
    return;
  }

  if (!form.reportValidity()) {
    return;
  }

  saveLead(form);
  form.classList.add("is-sending");
  form.reset();
  status.textContent = translations[activeLang]["form.success"] || translations.en["form.success"];
  window.setTimeout(() => form.classList.remove("is-sending"), 900);
});

const backToTop = document.querySelector(".back-to-top");

function updateBackToTop() {
  backToTop.classList.toggle("visible", window.scrollY > 520);
}

window.addEventListener("scroll", updateBackToTop, { passive: true });
updateBackToTop();

const revealItems = document.querySelectorAll(
  ".split-section, .comparison-card, .model-section .section-heading, .spec-card, .option-studio, .render-gallery figure, .content-grid article, .guide-grid article, .process-list li, .download-grid a, .lead-section, .faq-list details"
);

revealItems.forEach((item) => item.classList.add("reveal"));

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in-view");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 }
);

revealItems.forEach((item) => revealObserver.observe(item));

const optionContent = {
  deck: ["options.deckTitle", "options.deckCopy"],
  shade: ["options.shadeTitle", "options.shadeCopy"],
  offgrid: ["options.offgridTitle", "options.offgridCopy"],
  storage: ["options.storageTitle", "options.storageCopy"]
};

function updateOption(option) {
  if (!document.querySelector("#optionTitle") || !document.querySelector("#optionCopy")) {
    return;
  }

  const [titleKey, copyKey] = optionContent[option] || optionContent.deck;
  document.querySelector("#optionTitle").textContent = translations[activeLang][titleKey] || translations.en[titleKey];
  document.querySelector("#optionCopy").textContent = translations[activeLang][copyKey] || translations.en[copyKey];
  document.querySelectorAll("[data-option]").forEach((button) => {
    button.classList.toggle("active", button.dataset.option === option);
  });
}

document.querySelectorAll("[data-option]").forEach((button) => {
  button.addEventListener("click", () => updateOption(button.dataset.option));
});

document.querySelectorAll("[data-config-card]").forEach((card) => {
  card.addEventListener("click", () => {
    document.querySelectorAll("[data-config-card]").forEach((item) => item.classList.remove("active"));
    card.classList.add("active");
  });
});

document.querySelectorAll(".process-list li").forEach((item) => {
  item.addEventListener("click", () => {
    const wasActive = item.classList.contains("active");
    document.querySelectorAll(".process-list li").forEach((step) => {
      step.classList.remove("active");
      step.querySelector(".process-toggle")?.setAttribute("aria-expanded", "false");
    });

    if (!wasActive) {
      item.classList.add("active");
      item.querySelector(".process-toggle")?.setAttribute("aria-expanded", "true");
    }
  });
  item.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      item.click();
    }
  });
});

document.querySelectorAll(".process-toggle").forEach((button) => {
  button.setAttribute("aria-expanded", button.closest("li").classList.contains("active") ? "true" : "false");
  button.addEventListener("click", (event) => {
    event.stopPropagation();
    button.closest("li").click();
  });
});

document.querySelectorAll(".faq-list details").forEach((item) => {
  item.addEventListener("toggle", () => {
    if (!item.open) {
      return;
    }

    document.querySelectorAll(".faq-list details").forEach((otherItem) => {
      if (otherItem !== item) {
        otherItem.open = false;
      }
    });
  });
});

